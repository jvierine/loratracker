import assert from 'node:assert/strict';
import {decodeBinary27,gpsText,trackGps} from '../web/payload.mjs';
const f=decodeBinary27('bc340b0082978a42f83e80410c0006580c8d2558dfc147324d2cbc');
assert.equal(f.latitude_deg,69.29591369628906);
assert.equal(f.longitude_deg,16.030746459960938);
assert.equal(f.time_counter_u16,11);
assert.equal(f.gps_coordinates_available,true);
assert.match(gpsText(f),/69.295914° N, 16.030746° E/);
const zero=decodeBinary27('bc34250000000000000000000000005d128c3912dcc1472e8700f6');
assert.equal(zero.gps_coordinates_available,false);
assert.match(gpsText(zero),/unavailable/);
const bytes=new Uint8Array(27),view=new DataView(bytes.buffer);
view.setFloat32(4,-33.875,true);view.setFloat32(8,-70.25,true);
const hex=()=>Buffer.from(bytes).toString('hex');
assert.match(gpsText(decodeBinary27(hex())),/33.875000° S, 70.250000° W/);
view.setFloat32(4,NaN,true);
assert.equal(decodeBinary27(hex()).gps_coordinates_available,false);
view.setFloat32(4,91,true);
assert.equal(decodeBinary27(hex()).gps_coordinates_available,false);
assert.equal(decodeBinary27('not hex'),null);
let track=trackGps(null,{utc:100,fields:f});
const jump={...f,latitude_deg:35};
track=trackGps(track,{utc:104,fields:jump});
assert.equal(track.fields.latitude_deg,f.latitude_deg);
assert.match(track.warning,/jump/);
track=trackGps(track,{utc:108,fields:f});
assert.equal(track.unchangedSince,100);
track=trackGps(track,{utc:112,fields:zero});
assert.equal(track.utc,108);
assert.match(track.warning,/unavailable/);
console.log('GPS payload checks passed: recorded coordinates, zero fix, signed hemispheres, invalid coordinates.');
